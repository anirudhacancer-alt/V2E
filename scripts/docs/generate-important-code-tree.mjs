import { promises as fs } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const repoRoot = path.resolve(__dirname, "../..");
const manifestPath = path.join(repoRoot, "docs/common/important-code-roots.json");
const outputPath = path.join(repoRoot, "docs/common/IMPORTANT-CODE-TREE.md");

const CHECK_MODE = process.argv.includes("--check");

function normalizeSlashes(value) {
  return value.replaceAll(path.sep, "/");
}

function shouldIncludeName(name, manifest) {
  if (manifest.excludeNames?.includes(name)) {
    return false;
  }
  return true;
}

function shouldIncludeFile(relativePath, manifest) {
  const normalized = normalizeSlashes(relativePath);
  if (manifest.excludeFiles?.includes(normalized)) {
    return false;
  }
  if (manifest.excludeSuffixes?.some((suffix) => normalized.endsWith(suffix))) {
    return false;
  }
  return true;
}

async function readManifest() {
  const raw = await fs.readFile(manifestPath, "utf8");
  const parsed = JSON.parse(raw);
  if (!Array.isArray(parsed.roots) || parsed.roots.length === 0) {
    throw new Error("docs/common/important-code-roots.json must define at least one root.");
  }
  return parsed;
}

async function statSafe(targetPath) {
  try {
    return await fs.stat(targetPath);
  } catch {
    return null;
  }
}

async function walkTree(absPath, relativePath, manifest, lines, prefix = "") {
  const entries = await fs.readdir(absPath, { withFileTypes: true });
  const filtered = entries
    .filter((entry) => shouldIncludeName(entry.name, manifest))
    .sort((a, b) => {
      if (a.isDirectory() !== b.isDirectory()) {
        return a.isDirectory() ? -1 : 1;
      }
      return a.name.localeCompare(b.name);
    });

  filtered.forEach((entry, index) => {
    const isLast = index === filtered.length - 1;
    const branch = isLast ? "\\- " : "|- ";
    const entryRelative = normalizeSlashes(path.join(relativePath, entry.name));
    if (entry.isDirectory()) {
      lines.push(`${prefix}${branch}${entry.name}/`);
    } else if (shouldIncludeFile(entryRelative, manifest)) {
      lines.push(`${prefix}${branch}${entry.name}`);
    } else {
      return;
    }
  });

  for (let i = 0; i < filtered.length; i += 1) {
    const entry = filtered[i];
    if (!entry.isDirectory()) {
      continue;
    }
    const isLast = i === filtered.length - 1;
    const nextPrefix = `${prefix}${isLast ? "   " : "|  "}`;
    const nextAbs = path.join(absPath, entry.name);
    const nextRel = path.join(relativePath, entry.name);
    await walkTree(nextAbs, nextRel, manifest, lines, nextPrefix);
  }
}

function renderHeader() {
  return [
    "# Important Code Tree",
    "",
    "Auto-generated index of key code and architecture files in this monorepo.",
    "",
    "- Generated by `pnpm docs:tree:update`",
    "- Source manifest: `docs/common/important-code-roots.json`",
    "",
    "> Do not edit this file manually. Update the manifest or tree script instead.",
    "",
  ];
}

async function renderImportantFiles(manifest) {
  const lines = ["## Important Top-Level Files", ""];
  const fileLines = [];
  for (const filePath of manifest.importantFiles ?? []) {
    const absPath = path.join(repoRoot, filePath);
    const exists = await statSafe(absPath);
    const marker = exists ? "" : " (missing)";
    fileLines.push(`- \`${normalizeSlashes(filePath)}\`${marker}`);
  }
  lines.push(...fileLines, "");
  return lines;
}

async function renderRootSection(root, manifest) {
  const rel = normalizeSlashes(root.path);
  const labelSuffix = root.label ? ` - ${root.label}` : "";
  const absPath = path.join(repoRoot, rel);
  const stats = await statSafe(absPath);
  const lines = [`## \`${rel}\`${labelSuffix}`, ""];

  if (!stats || !stats.isDirectory()) {
    lines.push("_Directory missing_", "");
    return lines;
  }

  const treeLines = [`${rel}/`];
  await walkTree(absPath, rel, manifest, treeLines);
  lines.push("```text", ...treeLines, "```", "");
  return lines;
}

async function buildOutput() {
  const manifest = await readManifest();
  const lines = renderHeader();
  lines.push(...(await renderImportantFiles(manifest)));
  for (const root of manifest.roots) {
    lines.push(...(await renderRootSection(root, manifest)));
  }
  return `${lines.join("\n").trimEnd()}\n`;
}

async function main() {
  const content = await buildOutput();
  if (CHECK_MODE) {
    const existing = await fs.readFile(outputPath, "utf8").catch(() => "");
    if (existing !== content) {
      console.error(
        "docs/common/IMPORTANT-CODE-TREE.md is out of date.\nRun: pnpm docs:tree:update"
      );
      process.exit(1);
    }
    console.log("docs/common/IMPORTANT-CODE-TREE.md is up to date.");
    return;
  }

  await fs.writeFile(outputPath, content, "utf8");
  console.log("Updated docs/common/IMPORTANT-CODE-TREE.md");
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : String(error));
  process.exit(1);
});
